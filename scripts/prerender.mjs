// Writes _includes/prerender.html: plain semantic HTML of the homepage
// content (projects, awards) so crawlers that don't run JavaScript still see
// it. It sits inside <div id="root"> and React replaces it on mount.
//
//   npm run prerender        (re-run after editing projects.js / awards.js)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const BS = String.fromCharCode(92); // backslash, spelled out to keep the regex sources readable
const STR = `(?:'((?:[^'${BS}${BS}]|${BS}${BS}.)*)'|"((?:[^"${BS}${BS}]|${BS}${BS}.)*)")`;
const unq = (m, i) => (m[i] ?? m[i + 1] ?? '').replace(/[\\](.)/g, '$1');
const field = (src, name) => { const m = src.match(new RegExp(`${name}:[ 	]*${STR}`)); return m ? unq(m, 1) : ''; };

// Projects: split on each top-level `title:` so details() bodies don't matter.
const projSrc = read('assets/jsx/data/projects.js');
const projects = projSrc.split(/\n\s*\{\s*\n\s*title:/).slice(1).map((chunk) => {
  const c = 'title:' + chunk;
  return { title: field(c, 'title'), studio: field(c, 'studio'), badge: field(c, 'badge'), desc: field(c, 'desc') };
}).filter((p) => p.title);

// Awards: game/year headings with their org + category lines.
const awardSrc = read('assets/jsx/data/awards.js');
const awards = awardSrc.split(/\n\s*game:/).slice(1).map((chunk) => {
  const c = 'game:' + chunk.split(/\n  \},?\n/)[0];
  const wins = [...c.matchAll(new RegExp(`org:[ 	]*${STR},[ 	
]*category:[ 	]*${STR}`, 'g'))]
    .map((m) => ({ org: unq(m, 1), category: unq(m, 3) }));
  return { game: field(c, 'game'), year: field(c, 'year'), wins };
}).filter((a) => a.game);

const html = `<!-- GENERATED by scripts/prerender.mjs — do not edit by hand. -->
<main class="prerender" data-prerender>
  <h1>Carlos Hurtado — Senior Engineer &amp; Game Developer</h1>
  <p>VR game developer, Asgard's Wrath. Senior Engineer at Sneaky Devil Studios, previously Technical Lead Manager at Sanzaru Games (Oculus Studios, Meta). Shipping award-winning VR games since 2008, including Asgard's Wrath 2 (10/10, IGN). Based in San Mateo, California.</p>
  <h2>Game development projects</h2>
${projects.map((p) => `  <article><h3>${esc(p.title)}</h3><p>${esc(p.studio)}${p.badge ? ' — ' + esc(p.badge) : ''}</p><p>${esc(p.desc)}</p></article>`).join('\n')}
  <h2>Awards</h2>
${awards.map((a) => `  <h3>${esc(a.game)} (${esc(a.year)})</h3>\n  <ul>${a.wins.map((w) => `<li>${esc(w.org)}: ${esc(w.category)}</li>`).join('')}</ul>`).join('\n')}
  <h2>Art</h2>
  <p>Oil paintings, digital portraits and figure studies by Carlos Hurtado.</p>
  <h2>Links</h2>
  <ul>
    <li><a href="https://www.linkedin.com/in/carloshurtado">LinkedIn</a></li>
    <li><a href="https://github.com/c-hurtado">GitHub</a></li>
    <li><a href="/assets/Carlos_Hurtado_Resume.pdf">Resume (PDF)</a></li>
  </ul>
</main>
`;
fs.writeFileSync(path.join(ROOT, '_includes/prerender.html'), html);
console.log(`prerender.html: ${projects.length} projects, ${awards.length} award groups`);
